import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

object AlunaSettings {
    var isVoiceAnimationEnabled by mutableStateOf(true)
    var currentLanguage by mutableStateOf("en")
    var isGaplessPlaybackEnabled by mutableStateOf(true)
    var crossfadeDurationSeconds by mutableStateOf(3) // Default 3 seconds
    var isShakeToSkipEnabled by mutableStateOf(true)
    var shakeSensitivity by mutableStateOf(12.0f)
    var isOnboardingCompleted by mutableStateOf(false)

    fun init(context: android.content.Context) {
        val prefs = context.getSharedPreferences("aluna_settings", android.content.Context.MODE_PRIVATE)
        isOnboardingCompleted = prefs.getBoolean("onboarding_completed", false)
        currentLanguage = prefs.getString("language", null) ?: run {
            val deviceLang = java.util.Locale.getDefault().language
            if (deviceLang in listOf("ru", "be", "tg")) deviceLang else "en"
        }
    }

    fun saveOnboardingCompleted(context: android.content.Context, completed: Boolean) {
        isOnboardingCompleted = completed
        context.getSharedPreferences("aluna_settings", android.content.Context.MODE_PRIVATE)
            .edit()
            .putBoolean("onboarding_completed", completed)
            .apply()
    }

    fun getLanguageName(): String = when (currentLanguage) {
        "en" -> "English"
        "ru" -> "Русский"
        "be" -> "Беларуская"
        "tg" -> "Тоҷикӣ"
        else -> "English"
    }
}

